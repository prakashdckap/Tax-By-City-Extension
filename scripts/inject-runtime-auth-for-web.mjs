#!/usr/bin/env node
/**
 * Production build helper (not a one-off test script).
 * Writes web-src/src/generatedRuntimeAuth.js from .env:
 *   RUNTIME_AUTH_BASE64, or RUNTIME_USERNAME + RUNTIME_PASSWORD (Base64(username:password))
 * Invoked automatically via npm run build / npm run deploy.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const envPath = path.join(root, '.env')
const outPath = path.join(root, 'web-src', 'src', 'generatedRuntimeAuth.js')

function loadEnv (file) {
  const out = {}
  if (!fs.existsSync(file)) return out
  const text = fs.readFileSync(file, 'utf8')
  for (const line of text.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq <= 0) continue
    const key = trimmed.slice(0, eq).trim()
    let v = trimmed.slice(eq + 1).trim()
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1)
    }
    out[key] = v
  }
  return out
}

function computeBase64 (env) {
  let b = (env.RUNTIME_AUTH_BASE64 || '').trim()
  if (b) return b
  const u = (env.RUNTIME_USERNAME || '').trim()
  const p = (env.RUNTIME_PASSWORD || '').trim()
  if (u && p) return Buffer.from(`${u}:${p}`, 'utf8').toString('base64')
  return ''
}

const env = loadEnv(envPath)
const b64 = computeBase64(env)

const content = `/**
 * Auto-generated by scripts/inject-runtime-auth-for-web.mjs from .env (RUNTIME_AUTH_BASE64 or RUNTIME_USERNAME/PASSWORD).
 * Do not edit by hand.
 */
export const RUNTIME_BASIC_AUTH_BASE64 = ${JSON.stringify(b64)}
`

fs.writeFileSync(outPath, content, 'utf8')
process.stdout.write(
  `inject-runtime-auth-for-web: ${outPath} ${b64 ? '(secret applied)' : '(empty — add RUNTIME_AUTH_BASE64 or RUNTIME_USERNAME/PASSWORD to .env)'}\n`
)
